#!/usr/bin/env node
/**
 * Generates the environment file from environment variables.
 *
 * Why: a production build must contain YOUR Supabase URL and anon key, but
 * those values must never be committed to Git.  Netlify (or any CI) therefore
 * runs this script before `ng build`, reading the values from its own
 * environment-variable store.
 *
 * Usage
 *   SUPABASE_URL=https://xyz.supabase.co \
 *   SUPABASE_ANON_KEY=eyJhbGciOi...      \
 *   node scripts/set-env.mjs --production
 *
 * Options
 *   --production   write src/environments/environment.production.ts (default:
 *                  writes environment.ts for local development)
 *   --dry-run      print what would be written, change nothing
 *
 * Optional variables
 *   COLLEGE_EMAIL_DOMAIN   e.g. examplecollege.edu (empty = accept any domain)
 *   APP_NAME               display name
 *   SUPPORT_EMAIL          Lost & Found desk address
 *   MATCH_MIN_SCORE        default 40
 *   PAGE_SIZE              default 9
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const args = process.argv.slice(2);
const production = args.includes('--production');
const dryRun = args.includes('--dry-run');

const url = (process.env.SUPABASE_URL ?? '').trim();
const key = (process.env.SUPABASE_ANON_KEY ?? '').trim();

if (!url || !key) {
  console.error(
    [
      '✖ SUPABASE_URL and/or SUPABASE_ANON_KEY are missing.',
      '',
      'Locally:',
      '  SUPABASE_URL=https://your-project.supabase.co \\',
      '  SUPABASE_ANON_KEY=your-anon-key \\',
      '  node scripts/set-env.mjs --production',
      '',
      'On Netlify: Site configuration → Environment variables → add both keys,',
      'then redeploy.  The build command in netlify.toml calls this script.',
    ].join('\n'),
  );
  process.exit(1);
}

if (!/^https?:\/\//.test(url)) {
  console.error(`✖ SUPABASE_URL must start with https:// (received "${url}").`);
  process.exit(1);
}

if (/service_role/i.test(key) || key.startsWith('sb_secret')) {
  console.error(
    [
      '✖ That looks like a SECRET key (service_role), not the public anon key.',
      '  Publishing it would give every visitor full database access.',
      '  Use the "anon public" key from Project settings → API.',
    ].join('\n'),
  );
  process.exit(1);
}

const domain = (process.env.COLLEGE_EMAIL_DOMAIN ?? '').trim().replace(/^@/, '');
const appName = (process.env.APP_NAME ?? 'Smart Campus Lost and Found').trim();
const supportEmail = (process.env.SUPPORT_EMAIL ?? '').trim();
const matchMinScore = Number(process.env.MATCH_MIN_SCORE ?? 40);
const pageSize = Number(process.env.PAGE_SIZE ?? 9);

const target = resolve(
  root,
  production ? 'src/environments/environment.production.ts' : 'src/environments/environment.ts',
);

const banner = production
  ? `/**
 * PRODUCTION environment — GENERATED by scripts/set-env.mjs.
 * Do not edit by hand and do not commit real keys: this file is produced at
 * build time from the SUPABASE_URL / SUPABASE_ANON_KEY environment variables.
 */`
  : `/**
 * DEVELOPMENT environment — GENERATED by scripts/set-env.mjs.
 * Safe to regenerate at any time: run the command again with new values.
 */`;

const contents = `${banner}
import type { AppEnvironment } from './environment.model';

export type { AppEnvironment };

export const environment: AppEnvironment = {
  production: ${production},
  supabaseUrl: '${url}',
  supabaseAnonKey: '${key}',
  collegeEmailDomain: '${domain}',
  matchMinScore: ${Number.isFinite(matchMinScore) ? matchMinScore : 40},
  pageSize: ${Number.isFinite(pageSize) ? pageSize : 9},
  appName: ${JSON.stringify(appName)},
  supportEmail: ${JSON.stringify(supportEmail)},
};
`;

if (dryRun) {
  console.log(`--- would write ${target} ---\n${contents}`);
  process.exit(0);
}

try {
  readFileSync(target, 'utf8');
} catch {
  console.warn(`! ${target} does not exist yet — creating it.`);
}

writeFileSync(target, contents, 'utf8');

console.log(`✔ Wrote ${target.replace(root + '/', '')}`);
console.log(`  Supabase URL        : ${url}`);
console.log(`  Anon key            : ${key.slice(0, 12)}… (${key.length} characters)`);
console.log(`  College e-mail rule : ${domain ? '@' + domain + ' only' : 'any domain (unrestricted)'}`);
console.log(`  Page size           : ${pageSize}   Match minimum: ${matchMinScore}`);
